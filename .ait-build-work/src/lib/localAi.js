function randomPick(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function getStageLabel(stageId) {
  if (stageId === "reaction") return "\uBC18\uC751 \uC18D\uB3C4";
  if (stageId === "focus") return "\uC120\uD0DD\uC801 \uC8FC\uC758";
  if (stageId === "flow") return "\uC9C0\uC18D \uC9D1\uC911";
  return "\uC9D1\uC911\uB825";
}

